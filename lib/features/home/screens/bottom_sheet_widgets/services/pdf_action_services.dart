import 'dart:async';
import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../../../../../core/services/pdf_generator_service.dart';
import '../loading_dialog.dart';

class PdfActionsService {
  Future<void> generateAndShowPdf({
    required BuildContext context,
    required Map<String, dynamic> scan,
    required Function(String) onError,
    required Function(File) onSuccess,
  }) async {
    // Close bottom sheet
    if (Navigator.canPop(context)) Navigator.pop(context);
    await Future.delayed(const Duration(milliseconds: 300));

    if (!context.mounted) return;
    showDialog(context: context, barrierDismissible: false, builder: (_) => const LoadingDialog());

    try {
      final pdfFile = await PdfShareService.generateScanPdf(scan).timeout(const Duration(seconds: 30));
      if (!context.mounted) return;
      Navigator.of(context, rootNavigator: true).pop();
      onSuccess(pdfFile);
    } on TimeoutException {
      onError('PDF generation timed out. Please try again.');
    } catch (e, s) {
      debugPrint('PDF Error: $e\n$s');
      onError('Failed to generate PDF: ${e.toString()}');
    }
  }

  Future<void> copyResultsToClipboard(BuildContext context, Map<String, dynamic> scan) async {
    final diagnosis = scan['diagnosis']?.toString() ?? 'Unknown';
    final confidence = double.tryParse(scan['confidence']?.toString() ?? '0') ?? 0.0;
    final date = _formatDate(scan['timestamp']);

    final text = '''
═══════════════════════════════
    AGRIGUARD SCAN REPORT
═══════════════════════════════

Diagnosis: $diagnosis
Confidence: ${confidence.toStringAsFixed(1)}%
Date: $date

RECOMMENDATIONS:
${_getRecommendations(diagnosis, confidence)}

───────────────────────────────
Generated by AgriGuard Plant Health Scanner
'''.trim();

    await Clipboard.setData(ClipboardData(text: text));
    if (!context.mounted) return;

    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: const Row(children: [Icon(Icons.check_circle_rounded, color: Colors.white, size: 20), SizedBox(width: 12), Text('Results copied to clipboard!')]),
        backgroundColor: const Color(0xFF10B981),
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
      ),
    );
  }

  String _getRecommendations(String diagnosis, double confidence) {
    final recs = <String>[];
    if (confidence < 60) {
      recs.addAll(['• Rescan with better lighting conditions', '• Ensure the leaf is clearly in focus', '• Avoid shadows or glare on the plant']);
    }
    if (diagnosis.toLowerCase().contains('healthy')) {
      recs.addAll(['• Continue your regular care routine', '• Monitor plant health weekly', '• Maintain consistent watering schedule']);
    } else {
      recs.addAll(['• Isolate affected plant if possible', '• Consult with a local agricultural expert', '• Document any changes in symptoms']);
    }
    return recs.join('\n');
  }

  String _formatDate(dynamic timestamp) {
    try {
      DateTime? dt;
      if (timestamp is int) {
        dt = DateTime.fromMillisecondsSinceEpoch(timestamp);
      } else if (timestamp is String) dt = DateTime.tryParse(timestamp);
      else if (timestamp is DateTime) dt = timestamp;
      return dt != null ? '${dt.day}/${dt.month}/${dt.year} ${dt.hour}:${dt.minute.toString().padLeft(2, '0')}' : 'Unknown';
    } catch (e) {
      return 'Unknown';
    }
  }
}