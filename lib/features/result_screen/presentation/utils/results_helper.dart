import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import '../../../../core/constants/app_routes.dart';

/// Helper class for results screen utilities
class ResultsHelper {
  /// Format timestamp to readable date
  static String formatTimestamp(dynamic timestamp) {
    if (timestamp == null) return 'Unknown date';

    try {
      DateTime date;

      if (timestamp is Timestamp) {
        date = timestamp.toDate();
      } else if (timestamp is String) {
        date = DateTime.tryParse(timestamp) ?? DateTime.now();
      } else {
        return 'Unknown date';
      }

      return '${date.day.toString().padLeft(2, '0')}/'
          '${date.month.toString().padLeft(2, '0')}/'
          '${date.year} '
          '${date.hour.toString().padLeft(2, '0')}:'
          '${date.minute.toString().padLeft(2, '0')}';
    } catch (e) {
      debugPrint('Timestamp format error: $e');
      return 'Invalid date';
    }
  }

  /// Format date only (no time)
  static String formatDateOnly(DateTime date) {
    return '${date.day.toString().padLeft(2, '0')}/'
        '${date.month.toString().padLeft(2, '0')}/'
        '${date.year}';
  }

  /// Handle back navigation based on context
  static void navigateBack(
      BuildContext context,
      Map<String, dynamic> scanData,
      ) {
    final previousRoute = scanData['previousRoute'] as String?;
    final fromCapture = scanData['fromCapture'] as bool? ?? false;

    if (fromCapture) {
      // From capture screen, go to scan tab
      Navigator.of(context).pushNamedAndRemoveUntil(
        AppRoutes.scan,
            (route) => false,
      );
    } else if (previousRoute != null) {
      // Navigate to specified previous route
      Navigator.of(context).pushNamedAndRemoveUntil(
        previousRoute,
            (route) => false,
      );
    } else {
      // Default navigation
      if (Navigator.of(context).canPop()) {
        Navigator.of(context).pop();
      } else {
        Navigator.of(context).pushNamedAndRemoveUntil(
          AppRoutes.home,
              (route) => false,
        );
      }
    }
  }

  /// Share results functionality
  static Future<void> shareResults(
      BuildContext context,
      Map<String, dynamic> scanData,
      ) async {
    try {
      final dateStr = _extractDateString(scanData['timestamp']);

      if (!context.mounted) return;

      // Build share text
      final shareText = _buildShareText(scanData, dateStr);

      // TODO: Implement actual sharing
      // Example with share_plus package:
      // await Share.share(shareText);

      // Temporary implementation
      _showShareDialog(context, shareText);
    } catch (e) {
      debugPrint('Share error: $e');
      if (context.mounted) {
        _showError(context, 'Failed to share results');
      }
    }
  }

  /// Extract date string from timestamp
  static String _extractDateString(dynamic timestamp) {
    try {
      if (timestamp is Timestamp) {
        return formatDateOnly(timestamp.toDate());
      } else if (timestamp is String && timestamp.contains('/')) {
        final parts = timestamp.split(' ');
        return parts[0];
      }
      return formatDateOnly(DateTime.now());
    } catch (e) {
      debugPrint('Date extraction error: $e');
      return formatDateOnly(DateTime.now());
    }
  }

  /// Build share text content
  static String _buildShareText(
      Map<String, dynamic> scanData,
      String dateStr,
      ) {
    return '''
Plant Disease Analysis Results

📅 Date: $dateStr
🌿 Plant: ${scanData['plantName'] ?? 'Unknown'}
🦠 Diagnosis: ${scanData['diagnosis'] ?? 'Unknown'}
📊 Confidence: ${scanData['confidence'] ?? 'N/A'}%
⚠️ Severity: ${scanData['severity'] ?? 'Unknown'}
💊 Treatment: ${scanData['treatment'] ?? 'Consult an expert'}

Generated by AgriCare
''';
  }

  /// Show share dialog (temporary implementation)
  static void _showShareDialog(BuildContext context, String text) {
    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Share Results'),
        content: SingleChildScrollView(
          child: Text(text),
        ),
        actions: [
          TextButton(
            onPressed: () {
              // Copy text to clipboard
              _copyToClipboard(context, text);
            },
            child: const Text('Copy to Clipboard'),
          ),
          TextButton(
            onPressed: () => Navigator.of(context).pop(),
            child: const Text('Close'),
          ),
        ],
      ),
    );
  }

  /// Copy text to clipboard with feedback
  static Future<void> _copyToClipboard(BuildContext context, String text) async {
    try {
      await Clipboard.setData(ClipboardData(text: text));

      // Close the dialog first
      Navigator.of(context).pop();

      // Then show success message
      if (context.mounted) {
        showSuccess(context, 'Results copied to clipboard!');
      }
    } catch (e) {
      debugPrint('Clipboard error: $e');
      if (context.mounted) {
        _showError(context, 'Failed to copy to clipboard');
      }
    }
  }

  /// Show error message
  static void _showError(BuildContext context, String message) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(message),
        backgroundColor: Colors.red,
        duration: const Duration(seconds: 2),
        behavior: SnackBarBehavior.floating,
      ),
    );
  }

  /// Show success message
  static void showSuccess(BuildContext context, String message) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(message),
        backgroundColor: Colors.green,
        duration: const Duration(seconds: 2),
        behavior: SnackBarBehavior.floating,
      ),
    );
  }

  /// Build network image widget
  static Widget buildNetworkImage(String imageUrl, ThemeData theme) {
    return Container(
      width: double.infinity,
      height: 250,
      margin: const EdgeInsets.symmetric(vertical: 8),
      decoration: BoxDecoration(
        borderRadius: BorderRadius.circular(12),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.1),
            blurRadius: 8,
            offset: const Offset(0, 2),
          ),
        ],
      ),
      child: ClipRRect(
        borderRadius: BorderRadius.circular(12),
        child: Image.network(
          imageUrl,
          fit: BoxFit.cover,
          loadingBuilder: (context, child, loadingProgress) {
            if (loadingProgress == null) return child;
            return Center(
              child: CircularProgressIndicator(
                value: loadingProgress.expectedTotalBytes != null
                    ? loadingProgress.cumulativeBytesLoaded /
                    loadingProgress.expectedTotalBytes!
                    : null,
              ),
            );
          },
          errorBuilder: (context, error, stackTrace) {
            debugPrint('Network image error: $error');
            return buildNoImagePlaceholder(theme);
          },
        ),
      ),
    );
  }

  /// Build no image placeholder
  static Widget buildNoImagePlaceholder(ThemeData theme) {
    return Container(
      height: 200,
      decoration: BoxDecoration(
        color: theme.colorScheme.surface.withValues(alpha: 0.1),
        borderRadius: BorderRadius.circular(12),
        border: Border.all(
          color: theme.colorScheme.outline.withValues(alpha: 0.2),
        ),
      ),
      child: Center(
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            Icon(
              Icons.photo_library_rounded,
              size: 48,
              color: theme.colorScheme.onSurface.withValues(alpha: 0.3),
            ),
            const SizedBox(height: 8),
            Text(
              'No image available',
              style: theme.textTheme.bodyMedium?.copyWith(
                color: theme.colorScheme.onSurface.withValues(alpha: 0.5),
              ),
            ),
          ],
        ),
      ),
    );
  }

  /// Direct copy to clipboard method (for use outside dialogs)
  static Future<void> copyResultsToClipboard(
      BuildContext context,
      Map<String, dynamic> scanData,
      ) async {
    try {
      final dateStr = _extractDateString(scanData['timestamp']);
      final shareText = _buildShareText(scanData, dateStr);

      await _copyToClipboard(context, shareText);
    } catch (e) {
      debugPrint('Copy results error: $e');
      if (context.mounted) {
        _showError(context, 'Failed to copy results');
      }
    }
  }
}