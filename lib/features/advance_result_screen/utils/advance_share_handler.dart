import 'dart:io';
import 'package:flutter/material.dart';
import 'package:share_plus/share_plus.dart';

class AdvancedShareHandler {
  static Future<void> shareResults({
    required BuildContext context,
    required Map<String, dynamic> analysisResult,
    required Map<String, dynamic> originalScanData,
    File? pdfFile,
  }) async {
    final data = analysisResult['data'] as Map<String, dynamic>;
    final source = analysisResult['source']?.toString() ?? 'Advanced AI';

    // Build share text
    final shareText = _buildShareText(data, source);

    try {
      if (pdfFile != null && await pdfFile.exists()) {
        // Share with PDF
        await Share.shareXFiles(
          [XFile(pdfFile.path)],
          text: shareText,
          subject: 'AgriGuard Advanced Analysis Report',
        );
      } else {
        // Share text only
        await Share.share(
          shareText,
          subject: 'AgriGuard Advanced Analysis',
        );
      }
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Row(
              children: [
                const Icon(Icons.error_outline, color: Colors.white),
                const SizedBox(width: 12),
                Expanded(
                  child: Text('Failed to share: ${e.toString()}'),
                ),
              ],
            ),
            backgroundColor: Colors.red,
            behavior: SnackBarBehavior.floating,
          ),
        );
      }
    }
  }

  static String _buildShareText(Map<String, dynamic> data, String source) {
    final buffer = StringBuffer();

    buffer.writeln('🌱 AGRIGUARD ADVANCED ANALYSIS REPORT');
    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln();

    buffer.writeln('📊 DIAGNOSIS SUMMARY');
    buffer.writeln('─────────────────────');
    buffer.writeln('🌿 Plant: ${data['plantName'] ?? 'Unknown'}');
    buffer.writeln('🦠 Disease: ${data['diseaseName'] ?? 'None Detected'}');
    buffer.writeln('⚠️ Severity: ${data['severity'] ?? 'N/A'}');
    if (data['confidence'] != null) {
      buffer.writeln('🎯 Confidence: ${data['confidence']}%');
    }
    buffer.writeln('🔍 Source: $source');
    buffer.writeln();

    // Symptoms
    if (data['symptoms'] != null && (data['symptoms'] as List).isNotEmpty) {
      buffer.writeln('👁️ SYMPTOMS DETECTED');
      buffer.writeln('─────────────────────');
      for (var symptom in (data['symptoms'] as List)) {
        buffer.writeln('• $symptom');
      }
      buffer.writeln();
    }

    // Treatment
    if (data['remediation'] != null && (data['remediation'] as List).isNotEmpty) {
      buffer.writeln('💊 TREATMENT RECOMMENDATIONS');
      buffer.writeln('─────────────────────────────');
      for (var i = 0; i < (data['remediation'] as List).length; i++) {
        buffer.writeln('${i + 1}. ${(data['remediation'] as List)[i]}');
      }
      buffer.writeln();
    }

    // Precautions
    if (data['precautions'] != null && (data['precautions'] as List).isNotEmpty) {
      buffer.writeln('🛡️ PREVENTIVE MEASURES');
      buffer.writeln('──────────────────────');
      for (var precaution in (data['precautions'] as List)) {
        buffer.writeln('• $precaution');
      }
      buffer.writeln();
    }

    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('Generated by AgriGuard');
    buffer.writeln('AI-Powered Plant Disease Detection');
    buffer.writeln();
    buffer.writeln('⚠️ Disclaimer: Consult agricultural experts for critical cases.');

    return buffer.toString();
  }
}