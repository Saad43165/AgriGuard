// lib/services/pdf_generator_service.dart
import 'dart:io';
import 'package:flutter/cupertino.dart';
import 'package:path_provider/path_provider.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

class PdfShareService {
  static Future<File> generateScanPdf(Map<String, dynamic> scan) async {
    try {
      debugPrint('Starting PDF generation process...');

      // Create PDF document
      final pdf = pw.Document();

      // Extract scan data
      final diagnosis = scan['diagnosis']?.toString() ?? 'Unknown Disease';
      final confidenceStr = scan['confidence']?.toString() ?? '0';
      final confidence = double.tryParse(confidenceStr) ?? 0.0;
      final timestamp = scan['timestamp'] ?? scan['timestampMillis'];
      final date = _formatDate(timestamp);

      debugPrint('PDF data - Diagnosis: $diagnosis, Confidence: $confidence, Date: $date');

      // Create PDF content
      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (pw.Context context) {
            return _buildPdfContent(diagnosis, confidence, date);
          },
        ),
      );

      debugPrint('PDF document structure created, saving to file...');

      // Use getApplicationDocumentsDirectory for better compatibility
      final directory = await getApplicationDocumentsDirectory();
      final fileName = 'AgriGuard_Report_${DateTime.now().millisecondsSinceEpoch}.pdf';
      final filePath = '${directory.path}/$fileName';

      debugPrint('Saving PDF to: $filePath');

      // Save PDF
      final bytes = await pdf.save();
      debugPrint('PDF bytes generated: ${bytes.length} bytes');

      final file = File(filePath);
      await file.writeAsBytes(bytes, flush: true);

      // Verify file was written
      final fileExists = await file.exists();
      final fileSize = await file.length();

      debugPrint('File exists: $fileExists, File size: $fileSize bytes');

      if (!fileExists || fileSize == 0) {
        throw Exception('PDF file was not created properly');
      }

      debugPrint('PDF generation completed successfully');
      return file;
    } catch (e, stackTrace) {
      debugPrint('Error in generateScanPdf: $e');
      debugPrint('Stack trace: $stackTrace');
      rethrow;
    }
  }

  // ... rest of the PDF building methods remain the same
  static pw.Widget _buildPdfContent(String diagnosis, double confidence, String date) {
    return pw.Padding(
      padding: const pw.EdgeInsets.all(25),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          // Header
          pw.Center(
            child: pw.Column(
              children: [
                pw.Text(
                  'LEAF DISEASE SCAN REPORT',
                  style: pw.TextStyle(
                    fontSize: 20,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.SizedBox(height: 8),
                pw.Text(
                  'AgriGuard - Plant Health Analysis',
                  style: pw.TextStyle(
                    fontSize: 12,
                    color: PdfColors.grey700,
                  ),
                ),
              ],
            ),
          ),

          pw.SizedBox(height: 30),
          _buildDivider(),
          pw.SizedBox(height: 20),

          // Scan Information
          _buildSectionHeader('SCAN INFORMATION'),
          pw.SizedBox(height: 15),

          _buildInfoRow('Diagnosis', diagnosis),
          _buildInfoRow('Confidence Level', '${confidence.toStringAsFixed(1)}%'),
          _buildInfoRow('Scan Date', date),
          _buildInfoRow('Reliability', _getReliabilityStatus(confidence)),

          pw.SizedBox(height: 25),

          // Confidence Analysis
          _buildSectionHeader('CONFIDENCE ANALYSIS'),
          pw.SizedBox(height: 15),
          _buildConfidenceBar(confidence),
          pw.SizedBox(height: 10),
          pw.Text(
            _getConfidenceDescription(confidence),
            style: pw.TextStyle(fontSize: 11, color: PdfColors.grey700),
          ),

          pw.SizedBox(height: 25),

          // Recommendations
          _buildSectionHeader('RECOMMENDATIONS'),
          pw.SizedBox(height: 15),
          ..._buildRecommendations(diagnosis, confidence),

          pw.Spacer(),

          // Footer
          _buildDivider(),
          pw.SizedBox(height: 10),
          pw.Center(
            child: pw.Column(
              children: [
                pw.Text(
                  'Generated by AgriGuard App',
                  style: pw.TextStyle(
                    fontSize: 10,
                    color: PdfColors.grey600,
                  ),
                ),
                pw.SizedBox(height: 4),
                pw.Text(
                  'Report Date: ${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
                  style: pw.TextStyle(
                    fontSize: 9,
                    color: PdfColors.grey500,
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildSectionHeader(String text) {
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(vertical: 8, horizontal: 12),
      decoration: pw.BoxDecoration(
        color: PdfColors.grey300,
        borderRadius: pw.BorderRadius.circular(4),
      ),
      child: pw.Text(
        text,
        style: pw.TextStyle(
          fontSize: 14,
          fontWeight: pw.FontWeight.bold,
        ),
      ),
    );
  }

  static pw.Widget _buildInfoRow(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 12),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 130,
            child: pw.Text(
              '$label:',
              style: pw.TextStyle(
                fontSize: 12,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              value,
              style: const pw.TextStyle(fontSize: 12),
            ),
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildConfidenceBar(double confidence) {
    final color = _getConfidenceColor(confidence);
    final status = _getConfidenceStatus(confidence);

    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Container(
          width: 400,
          height: 30,
          decoration: pw.BoxDecoration(
            border: pw.Border.all(color: PdfColors.grey500, width: 1),
            borderRadius: pw.BorderRadius.circular(4),
            color: PdfColors.grey200,
          ),
          child: pw.Row(
            children: [
              pw.Container(
                width: (confidence / 100) * 400,
                height: 30,
                decoration: pw.BoxDecoration(
                  color: color,
                  borderRadius: pw.BorderRadius.circular(3),
                ),
              ),
            ],
          ),
        ),
        pw.SizedBox(height: 8),
        pw.Text(
          '${confidence.toStringAsFixed(1)}% - $status',
          style: pw.TextStyle(
            fontSize: 12,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
      ],
    );
  }

  static List<pw.Widget> _buildRecommendations(String diagnosis, double confidence) {
    final items = <pw.Widget>[];

    // Add confidence-based recommendations
    if (confidence < 60) {
      items.add(_buildRecommendationItem('Consider rescanning with better lighting conditions'));
      items.add(_buildRecommendationItem('Ensure the leaf is clearly visible and in focus'));
      items.add(_buildRecommendationItem('Try scanning multiple leaves for better accuracy'));
    }

    // Add diagnosis-based recommendations
    if (diagnosis.toLowerCase().contains('healthy')) {
      items.add(_buildRecommendationItem('Continue regular monitoring of plant health'));
      items.add(_buildRecommendationItem('Maintain proper watering and nutrition schedule'));
      items.add(_buildRecommendationItem('Ensure adequate sunlight exposure'));
    } else {
      items.add(_buildRecommendationItem('Isolate affected plants to prevent disease spread'));
      items.add(_buildRecommendationItem('Consult with agricultural expert for treatment options'));
      items.add(_buildRecommendationItem('Consider appropriate fungicides or natural remedies'));
      items.add(_buildRecommendationItem('Monitor plant recovery progress regularly'));
    }

    return items;
  }

  static pw.Widget _buildRecommendationItem(String text) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 8),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Container(
            width: 8,
            height: 8,
            margin: const pw.EdgeInsets.only(top: 4, right: 8),
            decoration: const pw.BoxDecoration(
              color: PdfColors.grey700,
              shape: pw.BoxShape.circle,
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              text,
              style: const pw.TextStyle(fontSize: 11),
            ),
          ),
        ],
      ),
    );
  }

  static pw.Widget _buildDivider() {
    return pw.Container(
      height: 1,
      color: PdfColors.grey400,
    );
  }

  static PdfColor _getConfidenceColor(double confidence) {
    if (confidence >= 80) return PdfColors.green700;
    if (confidence >= 60) return PdfColors.orange700;
    return PdfColors.red700;
  }

  static String _getConfidenceStatus(double confidence) {
    if (confidence >= 80) return 'High Confidence';
    if (confidence >= 60) return 'Medium Confidence';
    return 'Low Confidence';
  }

  static String _getConfidenceDescription(double confidence) {
    if (confidence >= 80) return 'High confidence - Reliable result, action can be taken';
    if (confidence >= 60) return 'Medium confidence - Consider verification with expert';
    return 'Low confidence - Rescan recommended for accurate results';
  }

  static String _getReliabilityStatus(double confidence) {
    if (confidence >= 80) return 'Highly Reliable';
    if (confidence >= 60) return 'Moderately Reliable';
    return 'Needs Verification';
  }

  static String _formatDate(dynamic timestamp) {
    try {
      DateTime? dt;
      if (timestamp is int) {
        dt = DateTime.fromMillisecondsSinceEpoch(timestamp);
      } else if (timestamp is String) {
        dt = DateTime.tryParse(timestamp);
      } else if (timestamp is DateTime) {
        dt = timestamp;
      }

      if (dt != null) {
        return '${dt.day.toString().padLeft(2, '0')}/${dt.month.toString().padLeft(2, '0')}/${dt.year} at ${dt.hour.toString().padLeft(2, '0')}:${dt.minute.toString().padLeft(2, '0')}';
      }
    } catch (e) {
      debugPrint('Date formatting error: $e');
    }

    return 'Unknown date';
  }
}